const DICTS: Record<Lang, Record<MsgKey, string>> = {
  es: { ...es, ...ES3, ...ES4, ...ES5, ...AREA_ES },
  en: { ...en, ...EN3, ...EN4, ...EN5, ...AREA_EN },
};

const STORAGE_KEY = 'aurum.lang';

/** Values for `{name}` tokens in a string. */
export type MsgVars = Record<string, string | number>;

/** A plural pair: `<key>.one` / `<key>.other`. Only such keys are valid for `tn`. */
type PluralBase<K> = K extends `${infer B}.other` ? B : never;
export type PluralKey = PluralBase<MsgKey>;

/**
 * Replace every `{name}` token with `vars[name]`. A missing var leaves the token in place (and
 * warns in development) so a typo is visible on screen rather than silently blank.
 */
export function interpolate(template: string, vars?: MsgVars): string {
  if (!vars) return template;
  return template.replace(/\{([a-zA-Z0-9_]+)\}/g, (m, name: string) => {
    if (Object.prototype.hasOwnProperty.call(vars, name)) return String(vars[name]);
    if (process.env.NODE_ENV !== 'production') {
      console.warn(`i18n: missing var {${name}} for "${template}"`);
    }
    return m;
  });
}

function lookup(lang: Lang, key: string): string {
  const d = DICTS[lang] as Record<string, string>;
  const fallback = DICTS.es as Record<string, string>;
  return d[key] ?? fallback[key] ?? key;
}

/** `t` without a provider — for the few places that format outside React (toasts, titles). */
export function translate(lang: Lang, key: MsgKey, vars?: MsgVars): string {
  return interpolate(lookup(lang, key), vars);
}

const PLURAL_LOCALE: Record<Lang, string> = { es: 'es-MX', en: 'en-US' };

function pluralCategory(lang: Lang, n: number): 'one' | 'other' {
  try {
    return new Intl.PluralRules(PLURAL_LOCALE[lang]).select(n) === 'one' ? 'one' : 'other';
  } catch {
    return Math.abs(n) === 1 ? 'one' : 'other';
  }
}

/** `tn('common.days', 3)` → `'3 días'` via `common.days.one|.other` and `{n}`. */
export function translatePlural(lang: Lang, key: PluralKey, n: number, vars?: MsgVars): string {
  const cat = pluralCategory(lang, n);
  const full = `${key}.${cat}`;
  const template = lookup(lang, full);
  return interpolate(template === full ? lookup(lang, `${key}.other`) : template, { n, ...vars });
}

interface I18nValue {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: MsgKey, vars?: MsgVars) => string;
  tn: (key: PluralKey, n: number, vars?: MsgVars) => string;
}

const I18nContext = createContext<I18nValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  // `es` on first render on both server and client, so the static export hydrates cleanly;
  // the stored preference is applied in an effect.
  const [lang, setLangState] = useState<Lang>('es');

  useEffect(() => {
    try {
      const stored = window.localStorage.getItem(STORAGE_KEY);
      if (stored === 'en' || stored === 'es') setLangState(stored);
    } catch {
      /* storage blocked — the default is fine */
    }
  }, []);

  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);

  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    try {
      window.localStorage.setItem(STORAGE_KEY, l);
    } catch {
      /* ignore */
    }
  }, []);

  const t = useCallback((key: MsgKey, vars?: MsgVars) => translate(lang, key, vars), [lang]);
  const tn = useCallback((key: PluralKey, n: number, vars?: MsgVars) => translatePlural(lang, key, n, vars), [lang]);

  const value = useMemo(() => ({ lang, setLang, t, tn }), [lang, setLang, t, tn]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nValue {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error('useI18n must be used inside <I18nProvider>');
  return ctx;
}

export interface MoneyFormatter {
  /** `formatAmount` bound to the active language and the workspace's base currency. */
  fmt: (a: AmountLike, opts?: Omit<MoneyOptions, 'base'>) => string;
  base: string;
  lang: Lang;
}

/**
 * Money formatting bound to the workspace: the base currency renders as `$`, anything
 * else as `US$` / `MX$` / ISO code. Falls back to the language's home currency until the
 * workspace list has loaded.
 */
export function useMoney(): MoneyFormatter {
  const { lang } = useI18n();
  const { current } = useWorkspace();
  const base = (current?.base_currency ?? (lang === 'en' ? 'USD' : 'MXN')).toUpperCase();
  return useMemo(
    () => ({
      fmt: (a: AmountLike, opts?: Omit<MoneyOptions, 'base'>) => formatAmount(a, lang, { ...opts, base }),
      base,
      lang,
    }),
    [lang, base],
  );
}
